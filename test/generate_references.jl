# Offline, independent scalar oracles. Not part of runtests.jl.
# Regenerate: julia --project test/generate_references.jl
using QuadGK: quadgk

function origin_coefficient(n, c, k, modified)
    result = zero(c)
    for m in max(0, cld(k - n, 2)):600
        d = n + 2m
        term = binomial(big(d), k) * c^(d - k) /
            (big(2)^d * factorial(big(m)) * factorial(big(n + m)))
        !modified && isodd(m) && (term = -term)
        result += term
        abs(term) <= eps(c) * abs(result) && return result
    end
    error("Origin series did not converge")
end

function k_values(c, nmax)
    values = zeros(BigFloat, nmax + 1)
    for n in 0:1
        f(t) = begin
            d = 2c * sinh(t / 2)^2
            isfinite(d) ? exp(-d) * cosh(n * t) : zero(c)
        end
        values[n + 1], error = quadgk(
            f, zero(c), BigFloat(Inf);
            rtol = big(2)^(-750), order = 64
        )
        @assert error < big(2)^(-700) * abs(values[n + 1])
    end
    for n in 1:(nmax - 1)
        values[n + 2] = values[n] + 2n * values[n + 1] / c
    end
    return values
end

function k_coefficient(values, n, k)
    return sum(0:k) do j
        derivative = sum(binomial(big(j), m) * values[abs(n - j + 2m) + 1] for m in 0:j)
        binomial(big(k), j) * (-big(1) // 2)^j * derivative / factorial(big(k))
    end
end

# DLMF 10.25.2 (I origin series), 10.32.9 (K integral), 10.29 (derivatives).
# 1024 bits controls cancellation in the K neighboring-order derivatives.
setprecision(1024) do
    cases = (
        (:I, 50, 2, (0, 1, 12, 30)), (:K, 30, 2, (0, 1, 12)),
        (:K, 5, 0, (0, 1, 12)), (:J, 1 // 10, 2, (0, 1, 12)),
    )
    open(joinpath(@__DIR__, "support", "special_references.jl"), "w") do io
        println(
            io, "# Generated by test/generate_references.jl ",
            "from independent 1024-bit scalar formulas."
        )
        println(io, "const SPECIAL_REFERENCES = (")
        for (family, center, n, degrees) in cases
            c = BigFloat(center)
            values = family == :K ? k_values(c, n + maximum(degrees)) : nothing
            refs = map(degrees) do k
                family == :K && return k_coefficient(values, n, k)
                family == :J && return origin_coefficient(n, c, k, false)
                exp(-c) * sum(
                    (-1)^(k - j) * origin_coefficient(n, c, j, true) /
                        factorial(big(k - j)) for j in 0:k
                )
            end
            strings = string.(BigFloat.(refs; precision = 512))
            println(io, "    (:", family, ", ", repr(center), ", ", n, ", ", degrees, ", (")
            for value in strings
                chunks = collect(Iterators.partition(value, 64))
                for (j, chunk) in enumerate(chunks)
                    suffix = j == length(chunks) ? "," : " *"
                    println(io, "        \"", join(chunk), "\"", suffix)
                end
            end
            println(io, "    )),")
        end
        println(io, ")")
    end
end
